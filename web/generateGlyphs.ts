// Writes src/ui/glyphs.ts from design-export/glyphs/: every Material Symbols path the boards use
// and the Todoist rings, so they ship in the bundle and never load from the network (DESIGN.md ›
// Glyphs, icons and the mark). tests/glyphs.test.ts checks the file is current.
//
//   npm run glyphs
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';

const GLYPHS = new URL('../design-export/glyphs/', import.meta.url);
export const OUTPUT = fileURLToPath(new URL('./src/ui/glyphs.ts', import.meta.url));

interface IconJson {
  name: string;
  fill: number;
  wght: number;
  viewBox: string;
  d: string;
}

/** An SVG file's viewBox and inner markup, without the export's fixed size and colour. */
function svgParts(file: string): {viewBox: string; body: string} {
  const svg = fs.readFileSync(new URL(file, GLYPHS), 'utf8').trim();
  const open = /^<svg\b[^>]*>/.exec(svg);
  const viewBox = open && /viewBox="([^"]+)"/.exec(open[0]);
  if (!open || !viewBox || !svg.endsWith('</svg>')) throw new Error(`${file} isn't a single <svg> element`);
  return {viewBox: viewBox[1]!, body: svg.slice(open[0].length, -'</svg>'.length).replace(/><\/(circle|path)>/g, '/>')};
}

export function renderGlyphs(): string {
  const icons = JSON.parse(fs.readFileSync(new URL('icons.json', GLYPHS), 'utf8')) as Record<string, IconJson>;
  const viewBoxes = new Set(Object.values(icons).map(icon => icon.viewBox));
  if (viewBoxes.size !== 1) throw new Error(`icons.json mixes viewBoxes: ${[...viewBoxes].join(', ')}`);
  const names = Object.keys(icons).sort();
  const open = svgParts('task-open.svg');
  const done = svgParts('task-done.svg');
  if (open.viewBox !== done.viewBox) throw new Error('The task glyphs have different viewBoxes');
  return [
    '// Generated by web/generateGlyphs.ts from design-export/glyphs/. Don\'t edit: run `npm run glyphs`.',
    '// Material Symbols Rounded, weight 300, FILL 0 (`-fill` names are FILL 1), as SVG paths.',
    '',
    `export const ICON_VIEWBOX = ${JSON.stringify([...viewBoxes][0])};`,
    '',
    'export const ICONS = {',
    ...names.map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(icons[name]!.d)},`),
    '} as const;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
    '/** Todoist\'s glyphs: the open ring and darma\'s filled disc with the check knocked out. */',
    `export const TASK_GLYPHS = ${JSON.stringify({viewBox: open.viewBox, open: open.body, done: done.body}, null, 2).replace(/"(\w+)":/g, '$1:')} as const;`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  fs.writeFileSync(OUTPUT, renderGlyphs());
  console.log(`Wrote ${OUTPUT}`);
}
